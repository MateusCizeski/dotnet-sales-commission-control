using ApiBase.Domain.Entities;
using Domain.Enums;
using Domain.Exceptions;
using Domain.Validation;

namespace Domain.Entities
{
    /// <summary>
    /// Aggregate root: the invoice creates and recalculates its own commission, so a use case
    /// saves both with a single commit — there is never an invoice without a commission.
    /// Status flow: Pending → Approved | Cancelled; Approved → Cancelled (only while the commission is not paid).
    /// </summary>
    public class Invoice : EntityGuid
    {
        public const int CustomerNameMaxLength = 200;
        public const int NotesMaxLength = 500;

        /// <summary>Sequential number generated by the database (INV-0001).</summary>
        public string Number { get; private set; } = string.Empty;

        public DateTime IssueDate { get; private set; }
        public Guid SellerId { get; private set; }
        public string CustomerName { get; private set; } = string.Empty;

        /// <summary>Customer's Brazilian tax ID: CPF (11 digits) or CNPJ (14 digits), digits only.</summary>
        public string CustomerTaxId { get; private set; } = string.Empty;

        public decimal TotalAmount { get; private set; }
        public InvoiceStatus Status { get; private set; }
        public string? Notes { get; private set; }

        public Seller? Seller { get; private set; }
        public Commission Commission { get; private set; } = null!;

        protected Invoice() { }

        public Invoice(string number, Seller seller, DateTime issueDate, string customerName, string customerTaxId, decimal totalAmount, string? notes, DateTime now)
        {
            if (string.IsNullOrWhiteSpace(number))
            {
                throw new DomainException("Invoice number is required.");
            }

            var normalizedTaxId = NormalizeTaxId(customerTaxId);

            ValidateSeller(seller);
            ValidateCustomerName(customerName);
            ValidateCustomerTaxId(normalizedTaxId);
            ValidateTotalAmount(totalAmount);
            ValidateIssueDate(issueDate);
            ValidateNotes(notes);

            Number = number;
            IssueDate = issueDate;
            SellerId = seller.Id;
            Seller = seller;
            CustomerName = customerName;
            CustomerTaxId = normalizedTaxId;
            TotalAmount = totalAmount;
            Notes = notes;
            Status = InvoiceStatus.Pending;
            Commission = new Commission(this, seller.CommissionRate, now);
        }

        public void Approve()
        {
            if (Status != InvoiceStatus.Pending)
            {
                throw new DomainException($"Only pending invoices can be approved. Current status: {Status}.");
            }

            Status = InvoiceStatus.Approved;
        }

        /// <summary>Cancels the invoice and its pending commission.</summary>
        public void Cancel()
        {
            if (Status == InvoiceStatus.Cancelled)
            {
                throw new DomainException("Invoice is already cancelled.");
            }

            if (Commission.Status == CommissionStatus.Paid)
            {
                throw new DomainException("An invoice whose commission was already paid cannot be cancelled.");
            }

            Status = InvoiceStatus.Cancelled;

            if (Commission.Status == CommissionStatus.Pending)
            {
                Commission.Cancel();
            }
        }

        /// <summary>Changes seller and total amount and recalculates the commission with the new seller's rate.</summary>
        public void Update(Seller seller, decimal totalAmount, DateTime now)
        {
            if (Status != InvoiceStatus.Pending)
            {
                throw new DomainException("Only pending invoices can be changed.");
            }

            ValidateSeller(seller);
            ValidateTotalAmount(totalAmount);

            SellerId = seller.Id;
            Seller = seller;
            TotalAmount = totalAmount;
            Commission.Recalculate(totalAmount, seller.CommissionRate, now);
        }

        private static void ValidateSeller(Seller? seller)
        {
            if (seller == null)
            {
                throw new DomainException("Seller is required.");
            }

            if (!seller.IsActive)
            {
                throw new DomainException("An inactive seller cannot receive commissions.");
            }
        }

        private static void ValidateCustomerName(string customerName)
        {
            if (string.IsNullOrWhiteSpace(customerName))
            {
                throw new DomainException("Customer name is required.");
            }

            if (customerName.Length > CustomerNameMaxLength)
            {
                throw new DomainException($"Customer name must have at most {CustomerNameMaxLength} characters.");
            }
        }

        private static void ValidateCustomerTaxId(string customerTaxId)
        {
            if (string.IsNullOrWhiteSpace(customerTaxId))
            {
                throw new DomainException("Customer CPF/CNPJ is required.");
            }

            if (!CpfValidator.CpfIsValid(customerTaxId) && !CnpjValidator.CnpjIsValid(customerTaxId))
            {
                throw new DomainException("Customer CPF/CNPJ is invalid.");
            }
        }

        private static void ValidateTotalAmount(decimal totalAmount)
        {
            if (totalAmount <= 0)
            {
                throw new DomainException("Invoice total amount must be greater than zero.");
            }
        }

        private static void ValidateIssueDate(DateTime issueDate)
        {
            if (issueDate == default)
            {
                throw new DomainException("Issue date is required.");
            }
        }

        private static void ValidateNotes(string? notes)
        {
            if (!string.IsNullOrEmpty(notes) && notes.Length > NotesMaxLength)
            {
                throw new DomainException($"Notes must have at most {NotesMaxLength} characters.");
            }
        }

        private static string NormalizeTaxId(string? value)
        {
            return new string((value ?? string.Empty).Where(char.IsDigit).ToArray());
        }
    }
}
